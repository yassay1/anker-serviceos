"""Unified Agent tool envelope.

Every Agent tool returns a ``ToolResult``; the string handed to the model is
generated by ``to_prompt_text`` so the prompt contract stays stable while
evaluation and audit consume one structured schema.
"""

from dataclasses import dataclass, field
import json

TOOL_STATUSES = ("OK", "NOT_FOUND", "DEGRADED", "REJECTED", "RECORDED", "LOADED")


@dataclass(frozen=True)
class ToolResult:
    status: str
    items: list[str] = field(default_factory=list)
    references: list[dict] = field(default_factory=list)
    applicability: str = ""
    notes: list[str] = field(default_factory=list)
    payload: dict | None = None

    def __post_init__(self):
        if self.status not in TOOL_STATUSES:
            raise ValueError("tool_result_status_not_allowed")

    def to_prompt_text(self, max_chars: int | None = None) -> str:
        if self.payload is not None:
            text = json.dumps(self.payload, ensure_ascii=False)
        else:
            text = "\n\n".join([*self.notes, *self.items])
        if max_chars is not None:
            text = text[:max_chars]
        return text

    def to_model_value(self):
        return self.payload if self.payload is not None else self.to_prompt_text()

    def audit(self, tool: str) -> dict:
        return {
            "tool": tool,
            "status": self.status,
            "applicability": self.applicability,
            "references": self.references,
            "notes": self.notes,
        }
